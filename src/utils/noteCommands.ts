// Решает на клиенте, является ли сообщение командой блокнота: только для таких сообщений уходит токен входа.
// Сервер всё равно сам разбирает и проверяет каждую команду, поэтому список должен совпадать с
// backend/pet-chat/notes.py (parse). В JavaScript \b не работает с кириллицей, поэтому конец слова проверяется явно.
const END = '(?![а-яёa-z0-9_])';
const VERBS = 'запиши|сохрани|создай|сделай|занеси|внеси|добавь|найди|покажи|прочитай|исправь|измени|обнови|перепиши|поставь|установи|напомни|отключи|выключи|убери|отмени';
const NOTE_VERBS = 'запиши|сохрани|создай|сделай|занеси|внеси|добавь|найди|покажи|прочитай|исправь|измени|обнови|перепиши';
const NOTE_REF = 'заметк[а-яё]*\\s+(?:номер\\s+|№\\s*|#\\s*)?\\d{1,18}';
const NOT_A_BODY = `(?:заметк[а-яё]*|идею|запись|как|что|почему|зачем|где|когда|кто|сколько|ли|в|во|это|мне)${END}`;

const QUICK_CREATE = new RegExp(
  '^(?:' +
    `(?:(?:запиши|сохрани|добавь|занеси|внеси)\\s+(?:мне\\s+)?(?:это\\s+)?(?:в|во)\\s+(?:мой\\s+|моё\\s+|мои\\s+)?(?:блокнот|заметки|заметку)|запиши(?:\\s+мне)?(?=\\s*,?\\s+что(?:\\s|$))|сделай\\s+(?:мне\\s+)?(?:новую\\s+)?заметку)${END}` +
    '|(?:просто\\s+)?(?:запиши|сохрани|записать|сохранить)(?:\\s+мне)?(?:\\s*,\\s*пожалуйста)?(?:\\s*[:—–]|\\s+-\\s|(?=\\s*["«“]))' +
    `|(?:просто\\s+)?(?:запиши|сохрани)(?:\\s+мне)?(?:\\s*,\\s*пожалуйста)?\\s+(?!${NOT_A_BODY})(?=\\S)` +
    ')',
  'i',
);
const NOTE_NOUN = new RegExp(`^(?:${NOTE_VERBS})\\s+(?:мне\\s+)?(?:(?:новую|последнюю)\\s+)?(?:заметку|заметки|идею|запись)(?:\\s|:|$)`, 'i');
const REMIND_SET = new RegExp(`^(?:(?:поставь|установи|добавь|сделай)\\s+напоминание\\s+(?:для|к|на)\\s+|напомни\\s+(?:про|о|об)\\s+)${NOTE_REF}(?![0-9])`, 'i');
const REMIND_OFF = new RegExp(`^(?:отключи|выключи|убери|отмени)\\s+напоминание\\s+(?:для|к|у|на)\\s+${NOTE_REF}\\s*[.!]?$`, 'i');

export function isNoteCommand(message: string, name = ''): boolean {
  const names = ['кодик', 'питомец', ...(name && name.length <= 80 ? [name] : [])].map((n) => n.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'));
  const prefix = new RegExp(`^(?:эй\\s+)?(?:${names.join('|')})(?:\\s*[,!:]\\s*|\\s+(?=(?:пожалуйста|${VERBS})${END}))`, 'i');
  const text = String(message ?? '').trim().replace(prefix, '').replace(/^пожалуйста[,\s]+/i, '');
  return QUICK_CREATE.test(text) || REMIND_SET.test(text) || REMIND_OFF.test(text) || NOTE_NOUN.test(text);
}
