import { PetType } from '../store/petStore';

// AI Agent that responds based on pet's intelligence level
export function generatePetResponse(
  userMessage: string,
  petName: string,
  petType: PetType,
  intelligence: number,
  level: number
): string {
  const lowerMsg = userMessage.toLowerCase();

  // Basic greetings
  if (lowerMsg.match(/привет|здравствуй|хай|hello|hi/)) {
    return getGreeting(petName, petType, intelligence);
  }

  // Help/advice requests
  if (lowerMsg.match(/помо|совет|подска|help|advice/)) {
    return getAdvice(userMessage, petName, intelligence, level);
  }

  // Programming/tech questions
  if (lowerMsg.match(/код|програм|функци|перемен|цикл|массив|code|program|function|variable|loop|array/)) {
    return getTechAdvice(userMessage, petName, intelligence, level);
  }

  // Life advice
  if (lowerMsg.match(/жизн|смысл|цел|мотивац|устал|депресс|груст|life|meaning|purpose|motivation|tired|sad/)) {
    return getLifeAdvice(userMessage, petName, intelligence, level);
  }

  // Study/learning
  if (lowerMsg.match(/уч|учеб|экзамен|задач|study|exam|homework|learn/)) {
    return getStudyAdvice(userMessage, petName, intelligence, level);
  }

  // Health
  if (lowerMsg.match(/здоров|бол|болит|врач|health|sick|pain|doctor/)) {
    return getHealthAdvice(petName, intelligence, level);
  }

  // Default response based on intelligence
  return getDefaultResponse(userMessage, petName, petType, intelligence, level);
}

function getGreeting(name: string, type: PetType, intelligence: number): string {
  const petSounds: Record<PetType, string> = {
    cat: 'Мяу! 🐱',
    dog: 'Гав! 🐕',
    bird: 'Чирик! 🐦',
    fox: 'Тяв! 🦊',
    dragon: 'Рррр! 🐉',
    bunny: 'Писк! 🐰',
    panda: 'Урр! 🐼',
    owl: 'Угу! 🦉',
  };

  if (intelligence < 30) {
    return `${petSounds[type]} ${name} рад тебя видеть! *виляет хвостиком*`;
  } else if (intelligence < 60) {
    return `${petSounds[type]} Привет, друг! Я ${name}, и я очень рад что ты пришёл! Чем могу помочь?`;
  } else {
    return `${petSounds[type]} Здравствуйте! Я ${name}, ваш верный помощник. Рад снова вас видеть. Готов помочь с любыми вопросами! ✨`;
  }
}

