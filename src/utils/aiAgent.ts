function getDefaultResponse(message: string, name: string, type: PetType, intelligence: number, level: number): string {
  const petEmojis: Record<PetType, string> = {
    cat: '🐱', dog: '🐕', bird: '🐦', fox: '🦊',
    dragon: '🐉', bunny: '🐰', panda: '🐼', owl: '🦉',
  };

  if (intelligence < 20) {
    return `${petEmojis[type]} ${name} наклоняет голову... *${getRandomAction(type)}* Мне пока сложно понять, но я стараюсь! Покорми меня, и я стану умнее!`;
  } else if (intelligence < 40) {
    return `${petEmojis[type]} ${name} задумался над твоим сообщением... Интересная мысль! Я пока учусь, но мне кажется, что тут есть над чем подумать. Можешь рассказать подробнее?`;
  } else if (intelligence < 70) {
    return `${petEmojis[type]} ${name} размышляет... 🤔\n\nИнтересный вопрос! Вот что я думаю по этому поводу: важно рассмотреть ситуацию с разных сторон. Каждый имеет свою точку зрения, и истина часто где-то посередине. Попробуй взвесить все "за" и "против"!\n\n*${name} доволен, что смог помочь!*`;
  } else {
    return `${petEmojis[type]} ${name} даёт экспертный ответ! 🎯\n\nОтличный вопрос! Позвольте проанализировать:\n\nС одной стороны, "${message.slice(0, 30)}..." — это многогранная тема. Ключевые аспекты:\n\n1. **Контекст** — важно понимать полную картину\n2. **Приоритеты** — определите, что наиболее важно\n3. **Действие** — теория без практики бесполезна\n\nМой совет: начните с малого, но начните сегодня. Прогресс важнее совершенства!\n\nХотите, чтобы я разобрал что-то конкретнее? 🧠✨`;
  }
}

function getRandomAction(type: PetType): string {
  const actions: Record<PetType, string[]> = {
    cat: ['мурлычет', 'умывается лапкой', 'гоняет хвост'],
    dog: ['виляет хвостом', 'приносит мячик', 'склоняет голову'],
    bird: ['перелетает с ветки', 'чирикает мелодию', 'чистит перышки'],
    fox: ['хитро прищуривается', 'крутится вокруг хвоста', 'принюхивается'],
    dragon: ['выпускает колечко дыма', 'переливает чешуёй', 'хлопает крыльями'],
    bunny: ['шмыгает носом', 'прыгает от радости', 'чешет ушко'],
    panda: ['катается по спинке', 'жуёт бамбук', 'обнимает лапы'],
    owl: ['поворачивает голову', 'мудро моргает', 'расправляет крылья'],
  };
  const list = actions[type];
  return list[Math.floor(Math.random() * list.length)];
}

// Get pet mood based on stats
export function getPetMood(hunger: number, happiness: number, energy: number, health: number): string {
  const avg = (hunger + happiness + energy + health) / 4;
  if (avg > 80) return 'счастлив';
  if (avg > 60) return 'доволен';
  if (avg > 40) return 'нормально';
  if (avg > 20) return 'грустит';
  return 'плохо';
}
